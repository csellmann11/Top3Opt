include("hierarchical_run.jl")
include("compact_local.jl")
using Test

"""Check the local correction algebra independently of manufactured goal errors."""
function validate_compact_local()
    BLAS.set_num_threads(1)
    prepared = hierarchical_prepare(manufactured_problem(:cube_smooth),2)
    geometry = hierarchical_geometry(prepared.fan)
    geometric = compact_local_defects(prepared.mesh,prepared.fan,geometry)
    nd = size(geometry.K,1)
    checks = 0
    for include_hat in (false,true)
        collection = compact_local_blocks(prepared.mesh,prepared.fan,geometry;include_hat)
        accumulated = zeros(nd,6)
        for node in 1:prepared.fan.vertex_count
            ids,B = compact_local_basis(geometry,geometric,node;include_hat)
            isempty(ids) && continue
            Q = compact_local_energy_basis(geometry.K,ids,B)
            # Rank filtering must retain each supplied function, as a function.
            recovered = Q*(transpose(Q)*geometry.K[ids,ids]*B)
            @test norm(recovered-B) <= 2e-10*max(norm(B),eps())
            accumulated[ids,:] .+= B[:,1:6]
            checks += 1
        end
        target = copy(geometric.defects)
        for (edge,(a,b)) in enumerate(geometry.edges)
            target[geometry.vertex_count+edge,:] .-= (target[a,:]+target[b,:])/2
        end
        target[geometry.boundary,:] .= 0.0
        @test accumulated ≈ target atol=2e-13
        checks += 1

        # A residual generated by a function in one local block must be solved
        # exactly by that block. This also checks overlap-update bookkeeping.
        block = collection.blocks[cld(length(collection.blocks),2)]
        exact = zeros(nd)
        exact[block.ids] = block.basis*sin.(collect(1:size(block.basis,2)))
        rhs = geometry.K*exact
        solved = only(compact_local_sweeps(geometry.K,rhs,[block];
            checkpoints=(1,),free=geometry.free))
        @test norm(solved.x-exact) <= 2e-10*norm(exact)
        @test solved.residual_drift < 2e-12
        @test all(iszero,solved.x[geometry.boundary])
        checks += 3

        # Every symmetric sweep must decrease the SPD residual functional.
        rhs = sin.(collect(1:nd))
        rhs[geometry.boundary] .= 0.0
        solutions = compact_local_sweeps(geometry.K,rhs,collection.blocks;
            checkpoints=(1,2,4),free=geometry.free)
        previous = 0.0
        for solution in solutions
            x = solution.x
            value = dot(x,geometry.K*x)/2-dot(rhs,x)
            @test value <= previous+2e-10*max(abs(previous),1.0)
            @test all(iszero,x[geometry.boundary])
            @test solution.residual_drift < 2e-11
            previous = value
            checks += 3
        end
    end
    println("COMPACT_VALIDATION ",(;checks))
    return checks
end

if abspath(PROGRAM_FILE) == @__FILE__
    validate_compact_local()
end
